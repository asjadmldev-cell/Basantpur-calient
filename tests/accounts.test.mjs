import assert from 'node:assert/strict';
import { build } from 'esbuild';
const bundled = await build({ entryPoints: [new URL('../src/accounts-model.ts', import.meta.url).pathname], bundle: true, write: false, platform: 'node', format: 'esm' });
const { accountEntry, accountSummary } = await import('data:text/javascript;base64,' + Buffer.from(bundled.outputFiles[0].text).toString('base64'));
const bill = (id, price, received, extra = {}) => ({ id, customer: id, date: '19/11/2026', total: price, data: { items: [{ id: 'item', name: 'Product', qty: 1, unitPrice: price }], discount: 0, received, ...extra } });
const paid = bill('paid', 100, 100);
const partial = bill('partial', 1500, 500);
const due = bill('due', 100.25, 0);
const tax = bill('tax', 100, 59, { discount: 10, tax: { mode: 'split', rate: 18 } });
assert.deepEqual(accountSummary([]), { billed: 0, received: 0, due: 0, dueCount: 0, unknownCount: 0 });
assert.equal(accountEntry(paid).status, 'Paid');
assert.equal(accountEntry(partial).status, 'Partial');
assert.equal(accountEntry(due).status, 'Unpaid');
assert.equal(accountEntry(tax).total, 106.2, 'ledger uses full invoice amount including discount and tax');
assert.equal(accountEntry(tax).due, 47.2);
assert.deepEqual(accountSummary([paid, partial, due, tax]), { billed: 1806.45, received: 659, due: 1147.45, dueCount: 3, unknownCount: 0 });
assert.deepEqual(accountSummary([bill('one', .1, .1), bill('two', .2, .2)]), { billed: .3, received: .3, due: 0, dueCount: 0, unknownCount: 0 }, 'totals sum in paise');
const legacy = { id: 'legacy', total: 400, date: 'yesterday' };
assert.equal(accountEntry(legacy).status, 'Unknown');
assert.equal(accountEntry(legacy).received, null);
assert.deepEqual(accountSummary([paid, legacy]), { billed: 500, received: 100, due: 0, dueCount: 0, unknownCount: 1 }, 'do not invent payments or dues on old summaries');
const updated = structuredClone(partial); updated.data.received = 1500;
assert.equal(accountSummary([paid, updated]).due, 0, 'editing payment removes the outstanding balance');
assert.equal(accountSummary([paid]).billed, 100, 'removed receipts leave the totals');
console.log('Accounts checks passed: real invoice totals, paid/partial/unpaid, tax/discount, exact paise, payment edits, deletion and unknown legacy payments.');
