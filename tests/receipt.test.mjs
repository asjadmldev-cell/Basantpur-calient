import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
const code=ts.transpileModule(readFileSync(new URL('../src/receipt-model.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {calculateReceipt,validateReceipt,amountInWords,defaultStore,createReceiptId}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const items=[{id:'1',name:'SSD',sku:'SSD-1',qty:3,unitPrice:0.1},{id:'2',name:'RAM',sku:'RAM-1',qty:2,unitPrice:1250.25}];
const data={id:'TEST',issuedAt:'2026-11-08T00:00:00.000Z',store:defaultStore,customer:{name:'',phone:'',address:'',email:'',gstin:''},items,discount:100.3,received:2000,paymentMethod:'UPI',reference:'',notes:''};
assert.deepEqual(calculateReceipt(items,100.3,2000),{subtotal:2500.8,total:2400.5,balance:400.5,quantity:5});
assert.equal(validateReceipt(data),'');
assert.equal(calculateReceipt(items,0,2500.8).balance,0);
assert.ok(validateReceipt({...data,received:2400.51}));
assert.ok(validateReceipt({...data,discount:2500.81}));
assert.ok(validateReceipt({...data,discount:-1}));
assert.ok(validateReceipt({...data,received:Number.NaN}));
assert.ok(validateReceipt({...data,items:[]}));
assert.ok(validateReceipt({...data,store:{...defaultStore,address:''}}));
for(const qty of [0,1.5,-2,1000])assert.ok(validateReceipt({...data,items:[{...items[0],qty}]}));
for(const unitPrice of [-1,Infinity,10000001])assert.ok(validateReceipt({...data,items:[{...items[0],unitPrice}]}));
assert.equal(amountInWords(2400.5),'Rupees Two Thousand Four Hundred and Fifty Paise Only');
assert.equal(amountInWords(100000),'Rupees One Lakh Only');
assert.equal(amountInWords(0),'Rupees Zero Only');
assert.equal(amountInWords(199.999),'Rupees Two Hundred Only');
const ids=new Set(Array.from({length:100},()=>createReceiptId()));assert.equal(ids.size,100);
console.log('Receipt checks passed: exact totals, partial/full payments, invalid inputs, amount in words and unique IDs.');
